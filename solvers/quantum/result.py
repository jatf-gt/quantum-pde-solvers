"""
Defines the standardised data structures for solver outputs.

This module encapsulates the output data generated by single executions of 
both 1D and 2D linear system solvers. It provides unified interfaces for 
downstream analysis, plotting, and metric computation, seamlessly accommodating 
both classical (Thomas, NumPy) and quantum (HHL) algorithmic frameworks.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

import numpy as np


# ── 1D Solver Result Container ────────────────────────────────────────────────

@dataclass
class SolverResult:
    """
    Encapsulates the comprehensive data produced by a 1D solver execution.

    Attributes
    ----------
    u : np.ndarray
        Recovered physical solution vector of length N.
    solver : str
        Identifier of the applied solver methodology ('Thomas', 'HHL', or 'NumPy').
    raw_state : Optional[np.ndarray], default=None
        Raw quantum state amplitudes extracted directly from the b-register. 
        Exclusive to the quantum HHL implementation.
    prop_const : Optional[float], default=None
        Proportionality constant c satisfying the relation c * A * raw_state ≈ b. 
        Exclusive to the quantum HHL implementation.
    euclidean_residual : Optional[float], default=None
        Relative Euclidean residual computed as ||Au - b||_2 / ||b||_2.
    """
    u:                  np.ndarray
    solver:             str
    raw_state:          Optional[np.ndarray] = field(default=None, repr=False)
    prop_const:         Optional[float]      = None
    euclidean_residual: Optional[float]      = None


# ── 2D Solver Result Container ────────────────────────────────────────────────

@dataclass
class SolverResult2D:
    """
    Encapsulates the comprehensive data produced by a 2D line-Jacobi solver execution.

    Attributes
    ----------
    u : np.ndarray
        (N, N) recovered spatial solution field.
    solver : str
        Identifier of the applied 2D solver methodology ('Thomas-2D', 'HHL-2D', or 'NumPy-2D').
    iterations : int
        Total number of line-Jacobi iterations executed.
    converged : bool
        Boolean flag indicating whether the iteration update error successfully 
        diminished below the predefined tolerance threshold prior to reaching 
        the maximum iteration ceiling.
    iteration_errors : list[float]
        Sequential list recording the supremum norm of the iterative difference 
        (max|u^{n+1} - u^n|) at each step. This metric is strictly retained to 
        facilitate the reproduction of the convergence profile plots detailed 
        in the primary reference literature.
    euclidean_residual : Optional[float], default=None
        Relative Euclidean residual evaluated against the complete N²×N² coupled 
        system following iterative convergence, computed as: 
        ||A_full * u_flat - b_full||_2 / ||b_full||_2.
    """
    u:                  np.ndarray
    solver:             str
    iterations:         int
    converged:          bool
    iteration_errors:   list[float]
    euclidean_residual: Optional[float] = None

