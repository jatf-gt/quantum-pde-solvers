"""
Defines the standardised data structure for solver outputs.

This module encapsulates the output data generated by a single execution of 
a linear system solver, providing a unified interface for downstream analysis 
and metric computation regardless of the underlying algorithm (quantum or classical).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

import numpy as np


# ── Result Container ──────────────────────────────────────────────────────────

@dataclass
class SolverResult:
    """
    Encapsulates the comprehensive data produced by a solver execution.

    Attributes
    ----------
    u : np.ndarray
        Recovered physical solution vector of length N.
    solver : str
        Identifier of the applied solver methodology ('Thomas', 'HHL', or 'NumPy').
    raw_state : Optional[np.ndarray]
        Raw quantum state amplitudes extracted from the b-register. Exclusive to 
        the quantum solver implementations.
    prop_const : Optional[float]
        Proportionality constant c such that c * A * raw_state ≈ b. Exclusive to 
        the quantum solver implementations.
    euclidean_residual : Optional[float]
        Relative Euclidean residual computed as ||Au - b||_2 / ||b||_2.
    """
    u: np.ndarray
    solver: str
    raw_state: Optional[np.ndarray] = field(default=None, repr=False)
    prop_const: Optional[float] = None
    euclidean_residual: Optional[float] = None